export function noorOfTheDay() {
  const now = new Date();
  const dayIndex = Math.floor(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86400000);
  return { dua: DUAS[dayIndex % DUAS.length], hadees: HADEES[dayIndex % HADEES.length] };
}
